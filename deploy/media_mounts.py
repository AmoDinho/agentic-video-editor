"""Generate a Compose override that mounts each media folder read-only.

media-folders.txt holds one host path per line. Blank lines and lines starting
with # are ignored. Each folder is mounted at /media/<folder name>. Names that
collide get a numeric suffix. Source files are never writable from a container.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path


def read_folders(path: Path) -> list[Path]:
    if not path.is_file():
        return []
    folders: list[Path] = []
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        folders.append(Path(line).expanduser())
    return folders


def mount_name(folder: Path, used: set[str]) -> str:
    base = re.sub(r"[^A-Za-z0-9._-]+", "-", folder.name).strip("-") or "folder"
    name = base
    n = 2
    while name in used:
        name = f"{base}-{n}"
        n += 1
    used.add(name)
    return name


def render_override(folders: list[Path], export_dir: str) -> str:
    used: set[str] = set()
    lines = [
        "# Generated by deploy/media_mounts.py. Do not edit.",
        "services:",
        "  api:",
        "    volumes:",
    ]
    mounts = [f"      - {export_dir}:/exports"]
    for folder in folders:
        name = mount_name(folder, used)
        mounts.append(f"      - {folder}:/media/{name}:ro")
    if not mounts:
        mounts.append("      - ${EXPORT_DIR:-./exports}:/exports")
    lines.extend(mounts)
    lines.extend(
        [
            "  worker:",
            "    volumes:",
            *mounts,
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    root = Path(argv[1]) if len(argv) > 1 else Path(".")
    src = root / "media-folders.txt"
    dest = root / "docker-compose.override.yml"
    export_dir = "${EXPORT_DIR:-./exports}"
    dest.write_text(render_override(read_folders(src), export_dir))
    print(dest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
